#include<stdio.h>
int main(){

    int num1 = 20;
    int num2 = 10;
    int result = num1 + num2;

    printf("result = %d\n", result);
    printf("%d -  %d = %d\n", num1,num2,num1-num2);
    printf("%d *  %d = %d\n", num1,num2,num1*num2);
    printf("%d /  %d = %d\n", num1,num2,num1/num2);
    printf("%d %% %d = %d\n", num1,num2,num1%num2);

return 0;

}  