//Reational operator : < > <= >=  == !=
//  Binary operators
// operator return 0(false) or 1(true) */

#include<stdio.h>
int main(){

    int num1 = 25;
    int num2 = 50;

        printf("< : num1 < num2 %d\n", num1 < num2);
        printf("> : num1 > num2 %d\n", num1 > num2);
        printf("<= : num1 <= num2 %d\n", num1 <= num2);
        printf(">= : num1 >= num2 %d\n", num1 >= num2);
        printf("== : num1 == num2 %d\n", num1 == num2);
        printf("!= : num1 != num2 %d\n", num1 != num2); 

    return 0;
}